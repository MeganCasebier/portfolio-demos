// End-to-end: drives the demo the way a visitor would and checks each claim the page makes.
import { open, sleep } from "./cdp.mjs";
import { writeFileSync } from "node:fs";
const url = process.argv[2] || "http://localhost:8898/demos/rules-wrapper/";
const out = process.argv[3];
const width = +(process.argv[4] || 1440);
const b = await open(url, { width, height: 900 });
const log = []; const ok = (name, cond) => log.push(`${cond ? "ok  " : "FAIL"} ${name}`);
const q = (s) => b.ev(`document.querySelector(${JSON.stringify(s)})?.textContent?.trim()`);

ok("all six tests start not run", (await q(".tally")).includes("6 not run"));
await b.click(".cell:not(.cell--head)"); await sleep(250);
ok("clicking a read-only cell shows the tooltip", (await b.ev(`!document.getElementById("tip").hidden && document.getElementById("tip").textContent`) || "").includes("design couldn’t change its shape"));
await b.key("Escape");
await b.click('[data-action="run"]'); await sleep(250);
ok("run all: six pass", (await q(".tally")).includes("6 passed"));
await b.click('[data-action="edit"]'); await sleep(300);
ok("edit mode crosses the border", await b.ev(`document.querySelector(".core").classList.contains("is-editing")`));
ok("filters lock while editing", await b.ev(`document.querySelector(".fchip").disabled`));
await b.ev(`(()=>{const i=document.querySelector('.cell-in[data-row="0"][data-col="lossCount"]'); i.focus(); i.select();})()`);
await b.type(">= 3"); await sleep(250);
ok("editing row 1 flips a test red", (await q(".tally")).includes("1 failed"));
ok("changed rows lists row 1", (await q(".coverage")).includes("Row 1"));
ok("the failing card says what did not fire", (await q(".card--fail")).includes("did not fire"));
if (out) writeFileSync(out + "-1-flipped.png", await b.shot());
await b.ev(`(()=>{const i=document.querySelector('.cell-in[data-row="3"][data-col="lossAmount"]'); i.focus(); i.select();})()`);
await b.type("> big"); await sleep(200);
ok("an unreadable cell is flagged and blocks review", await b.ev(`document.querySelector("#to-review").disabled && !!document.querySelector("td.is-bad")`));
await b.ev(`(()=>{const i=document.querySelector('.cell-in[data-row="3"][data-col="lossAmount"]'); i.focus(); i.select();})()`);
await b.type("> 60000"); await sleep(200);
await b.ev(`(()=>{const i=document.querySelector('.cell-in[data-row="1"][data-col="riskScore"]'); i.focus(); i.select();})()`);
await b.type('== "E"'); await sleep(200);
ok("a changed row no test reaches says so, with Add test", (await q(".coverage .is-uncovered"))?.includes("No test triggers this row"));
await b.click('[data-action="to-review"]'); await sleep(300);
ok("review shows the diff", (await q(".diff")).includes("Row 1"));
await b.click('[data-action="submit"]'); await sleep(250);
ok("submit without a record is refused, three errors", (await b.ev(`document.querySelectorAll(".field-err").length`)) === 3);
await b.ev(`document.getElementById("f-date").value="2026-11-15"; document.getElementById("f-date").dispatchEvent(new Event("input",{bubbles:true}))`);
await b.click("#f-note"); await b.type("Two losses no longer refer on their own.", { cps: 40 });
await b.ev(`const s=document.getElementById("f-approver"); s.value="Jordan Hale"; s.dispatchEvent(new Event("change",{bubbles:true}))`);
if (out) writeFileSync(out + "-2-review.png", await b.shot());
await b.click('[data-action="submit"]'); await sleep(300);
ok("submitted: v2.2 In QA", (await q(".context-ver")).includes("In QA"));
await b.click('[data-action="pass-qa"]'); await sleep(250);
ok("QA passed: Ready for approval", (await q(".context-ver")).includes("Ready for approval"));
await b.click('[data-action="approve"]'); await sleep(250);
await b.click('[data-action="versions"]'); await sleep(250);
ok("approved: v2.2 Active, v2.1 Inactive", (await q(".versions")).match(/v2\.2\s*Active/) && (await q(".versions")).match(/v2\.1\s*Inactive/));
ok("no Approved status anywhere", !(await b.ev(`document.body.innerText`)).match(/\bApproved\b/));
await b.click('[data-action="new-test"]'); await sleep(200);
await b.click('[data-action="form-grade"][data-v="C"]'); await sleep(100);
ok("unset fields count as missing", (await q("#form-preview")).includes("Missing information"));
await b.click('[data-action="run-fill"]'); await sleep(200);
await b.click('[data-action="save-test"]'); await sleep(200);
ok("new test saved and run", (await q(".tally")).includes("7") || (await q(".tally")).match(/\d+ passed/));
await b.ev(`[...document.querySelectorAll('[data-action="delete"]')].forEach(x=>x.click())`); await sleep(100);
for (let i = 0; i < 10; i++) { const n = await b.ev(`document.querySelectorAll('[data-action="delete"]').length`); if (!n) break; await b.ev(`document.querySelector('[data-action="delete"]').click()`); await sleep(40); }
ok("empty state appears", (await q(".panel")).includes("No tests yet"));
await b.click('.empty--panel [data-action="generate"]'); await sleep(200);
await b.click('[data-action="keep-proposals"]'); await sleep(200);
ok("generate from rows: five tests, all pass", (await q(".tally")).includes("5 passed"));
await b.click('[data-action="filter"][data-value="Landlord"]'); await sleep(150);
await b.click('[data-action="filter"][data-value="Eligibility"]'); await sleep(150);
ok("filters can reach an empty state", (await q(".groups")).includes("No groups match"));
ok("page has no horizontal scroll", await b.ev(`document.documentElement.scrollWidth <= innerWidth`));
ok("no script errors", b.errors.length === 0);
console.log(log.join("\n")); if (b.errors.length) console.log(b.errors);
b.close(); process.exit(log.some((l) => l.startsWith("FAIL")) ? 1 : 0);
